/**
 * 1 หน่วยโลก ≈ 1 เมตร (นิยามใน config.js) — ต่ำกว่ากิโลแสดงเมตรเต็มให้เลขวิ่ง
 * ทุกเมตร (ความรู้สึก "กำลังคืบหน้า") พอขึ้นกิโลค่อยเปลี่ยนหน่วยให้ตัวเลขไม่ยาวจนล้นแถว
 */
export function formatDistance(meters) {
  const m = Math.max(0, Math.floor(meters));
  if (m < 1000) return `${m} ม.`;
  const km = m / 1000;
  return `${km.toFixed(km < 10 ? 2 : 1)} กม.`;
}
