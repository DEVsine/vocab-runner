/**
 * cheats.js — "โหมดทดลอง" สำหรับบัญชีทดสอบ (ปลดด้วยรหัสลับในร้านค้า)
 *
 * ── ทำไมต้องมี และทำไมต้องแยกไฟล์ ──
 * การทดสอบเกมที่มีของสะสมมีคอขวดเดียวกันเสมอ: กว่าจะได้ของมาทดสอบต้องเล่นจริงเป็นชั่วโมง
 * (เก็บ 1200 เหรียญเพื่อดูว่าดาบไลต์เซเบอร์เรนเดอร์ถูกไหม, เก็บดาว 5 ดวงเพื่อดูด่านโบนัส
 * ของธีมที่เพิ่งแก้) — ผลคือคนแก้เกมจะ "ไม่ตรวจ" ส่วนที่เข้าถึงยาก แล้วบั๊กก็หลุดไปถึงผู้เล่น
 *
 * ทางแก้คือเปิดประตูลัดไว้ให้คนทดสอบ แต่ต้องอยู่หลังรหัสและ **ประกาศตัวชัดเจน**
 * ว่ากำลังเปิดอยู่ ไม่ใช่ซ่อนเงียบ ๆ — ของลับที่มองไม่เห็นว่าเปิดอยู่คือที่มาของ
 * รายงานบั๊กที่ผิดพลาด ("ทำไมคะแนนฉันเยอะจัง" / "ทำไมด่านโบนัสมาเร็วผิดปกติ")
 *
 * เก็บสถานะแยกจาก wallet/srs โดยตั้งใจ — ล้างโหมดทดลองทิ้งได้โดยไม่แตะข้อมูลการเรียนจริง
 */

const KEY = 'vocab-runner:cheats:v1';

/** เหรียญที่แจกต่อการใช้รหัส 1 ครั้ง — ใช้ซ้ำได้ ไม่จำกัดจำนวนครั้ง */
export const CHEAT_COINS = 9999;

function load() {
  try {
    return JSON.parse(localStorage.getItem(KEY)) || { enabled: false };
  } catch {
    return { enabled: false };
  }
}

function save(state) {
  try {
    localStorage.setItem(KEY, JSON.stringify(state));
  } catch { /* โหมดส่วนตัวเขียนไม่ได้ — โหมดทดลองจะอยู่แค่รอบนี้ */ }
}

export const cheats = {
  enabled: () => load().enabled === true,
  setEnabled(on) { save({ enabled: !!on }); },
};

/**
 * ตีความรหัสลับ → คืนสิ่งที่ต้องทำ (ตัวเรียกเป็นคนลงมือ)
 * แยก "แปลรหัส" ออกจาก "ลงมือทำ" เพื่อให้เพิ่มรหัสใหม่ได้โดยไม่ต้องแตะ UI
 */
export function redeem(raw) {
  const code = String(raw || '').trim().toLowerCase();
  if (!code) return null;

  if (code === '888') {
    return {
      action: 'coins',
      coins: CHEAT_COINS,
      enable: true,
      message: `🎁 รับ ${CHEAT_COINS.toLocaleString()} เหรียญแล้ว — เปิดโหมดทดลอง`,
      note: 'ในเกมจะมีปุ่ม ★ ให้กดเข้าด่านโบนัสได้ทันทีโดยไม่ต้องเก็บดาว',
    };
  }
  if (code === 'off' || code === 'ปิด') {
    return { action: 'disable', enable: false, message: 'ปิดโหมดทดลองแล้ว — เหรียญที่ได้มายังอยู่' };
  }
  return { action: 'invalid', message: 'รหัสไม่ถูกต้อง' };
}
