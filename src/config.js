/** หา answer window ปัจจุบันจากจำนวนด่านที่ผ่านมาแล้ว */
export function answerWindowFor(gatesPassed) {
  let seconds = CFG.answer.steps[0].seconds;
  for (const step of CFG.answer.steps) {
    if (gatesPassed >= step.afterGates) seconds = step.seconds;
  }
  return Math.max(CFG.answer.floor, seconds);
}

/**
 * ข้อนี้ควรอ่านคำออกเสียงตอนโจทย์ขึ้นจอหรือไม่
 *
 * โหมดฟัง / โจทย์วิชา / โหมดไทย = เสียงคือตัวโจทย์ ต้องอ่านเสมอ
 * โจทย์รูป = อ่านเมื่อผู้เล่นเปิด "พูดทุกครั้งที่ขึ้นคำ"
 *   (เด็กที่ยังอ่านอังกฤษไม่คล่องได้ยินแล้วเดาธงจากรูปคำได้)
 * มุกกวนไม่ใช่โจทย์คำศัพท์ — ไม่อ่าน
 */
export function shouldSpeakPrompt({ mode, speakAll = false } = {}) {
  if (mode === 'audio' || mode === 'subject' || mode === 'text') return true;
  if (mode === 'joke') return false;
  if (mode === 'image') return !!speakAll;
  return false;
}

/**
 * ถึงเวลา "อ่านโจทย์ซ้ำ" หรือยัง
 *
 * ⚠️ เงื่อนไข `speaking` คือหัวใจ ไม่ใช่ของแถม
 * โจทย์ deck วิชายาว 55 ตัวอักษร ใช้เวลาพูด ~4–5 วินาที แต่จุดอ่านซ้ำอยู่ที่
 * ~3.2 วินาที (45% ของหน้าต่าง 5.76 วิ) — คือ *ก่อน* เสียงแรกพูดจบ
 * ถ้าไม่กันไว้ ตัวอ่านซ้ำจะสั่ง speak() ทับขณะเครื่องยนต์ยังพูดอยู่ ทำให้เกิด
 * cancel() แล้ว speak() ต่อในทิกเดียวกัน ซึ่ง Chrome/WebKit ดรอปเสียงใหม่ทิ้งบ่อย
 * → ผู้เล่นได้ยินโจทย์ถูกตัดกลางประโยคแล้วเงียบ = "บางข้อไม่อ่าน"
 *
 * ความหมายที่ถูกต้องของการอ่านซ้ำคือ "ฟังไม่ทัน ขอฟังอีกรอบ" ไม่ใช่ "ขัดจังหวะตัวเอง"
 * ดังนั้นถ้ายังพูดอยู่ = ผู้เล่นกำลังได้ยินอยู่แล้ว ไม่ต้องซ้ำ และให้ถือว่า
 * ใช้สิทธิ์อ่านซ้ำของข้อนี้ไปแล้ว (คืน consume=true) เพื่อไม่ให้ไปแทรกทีหลัง
 * ตอนเวลาเหลือน้อยจนฟังไม่จบอยู่ดี
 *
 * @returns {{replay: boolean, consume: boolean}}
 */
export function replayDecision({ mode, ratio, speaking, alreadyReplayed, speakAll = false }) {
  if (alreadyReplayed) return { replay: false, consume: false };
  const at = mode === 'subject' ? CFG.question.subject.replayAt
    : shouldSpeakPrompt({ mode, speakAll }) ? CFG.question.audioReplayAt
    : null;
  if (at === null || ratio >= at) return { replay: false, consume: false };
  if (speaking) return { replay: false, consume: true };
  return { replay: true, consume: true };
}

/**
 * งบเวลา "รอให้เครื่องยนต์เริ่มพูด" ของข้อความหนึ่ง ๆ
 *
 * ⚠️ นี่คือจุดที่บั๊ก "deck ประวัติศาสตร์/วิชาไม่มีเสียงอ่าน" เกิดขึ้นจริง
 *
 * ของเดิมใช้ค่าคงที่ 450ms เป็นเส้นแบ่งว่า "เครื่องยนต์ค้างหรือยัง"
 * ความผิดพลาดเชิงความคิดคือเอา **เวลาหน่วง** (latency) มาใช้เป็นสัญญาณของ
 * **ความมีชีวิต** (liveness) ทั้งที่สองอย่างนี้ไม่ได้แปรผันตามกันเลย:
 *
 *   • เครื่องยนต์สังเคราะห์ "ทั้ง utterance" ให้เสร็จก่อนจึงเริ่มเล่น
 *     คำอังกฤษคำเดียว (10 ตัวอักษร) เริ่มพูดใน ~100ms
 *     ประโยคไทยของ deck วิชา (40–60 ตัวอักษร) ใช้เวลาตั้งท่านานกว่าหลายเท่า
 *   • เสียงที่ "เย็น" (เพิ่งถูกใช้ครั้งแรกในเซสชัน) ต้องโหลดข้อมูลเสียงจากดิสก์
 *     เสียงอังกฤษของระบบอุ่นอยู่แล้วเพราะ OS ใช้มันตลอด — เสียงไทยไม่ใช่
 *
 * ผลคือโจทย์วิชาข้อแรกชน 450ms แทบทุกครั้ง watchdog จึงสั่ง cancel() ใส่
 * เสียงที่กำลังจะพูดออกมาดี ๆ แล้วลองใหม่ ซึ่ง (ก) ผู้เล่นได้ยินเสียงถูกตัด
 * (ข) การ cancel รัว ๆ คือสาเหตุที่ทำให้ Chrome/WebKit ค้างทั้งเซสชัน
 * — ตัว watchdog ที่มีไว้กันอาการค้าง กลายเป็นคนสร้างอาการค้างเสียเอง
 *
 * บทเรียน: ถ้าจะตั้ง timeout ให้กับงานที่ "เวลาแปรตามขนาดของงาน"
 * ค่าคงที่จะถูกเสมอสำหรับงานเล็ก และผิดเสมอสำหรับงานใหญ่
 */
export function speechGraceMs(text = '') {
  const a = CFG.audio;
  return Math.min(
    a.speechStartGraceMaxMs,
    a.speechStartGraceMs + text.length * a.speechStartGracePerCharMs,
  );
}

/**
 * watchdog ควรทำอะไรต่อ เมื่อครบงบเวลารอเสียงแรกแล้วยังไม่ได้ยิน onstart
 *
 * กุญแจคือ "ถามเครื่องยนต์เอง" ว่ารับงานไปหรือยัง (speaking || pending):
 *   • busy = รับงานไปแล้ว แค่ยังตั้งท่าไม่เสร็จ → รอต่อ ห้าม cancel เด็ดขาด
 *   • idle = งานหายไปเงียบ ๆ (อาการพังที่ watchdog ควรจับจริง ๆ) → ลองใหม่
 * แยกสองกรณีนี้ออกจากกันคือทั้งหมดของการแก้บั๊กนี้
 *
 * @param {{started:boolean, engineBusy:boolean, retried:boolean, expired:boolean}} s
 * @returns {'ok'|'wait'|'retry'|'giveup'}
 */
export function speechWatchdogDecision({ started, engineBusy, retried, expired }) {
  if (started) return 'ok';
  if (engineBusy && !expired) return 'wait';   // ช้า ≠ ค้าง
  return retried ? 'giveup' : 'retry';
}

/** พรีเซ็ตโหมดเสียงโค้ช — ไม่รู้จักชื่อโหมด = กลับไปโหมดตั้งต้นเสมอ */
export function voiceModeById(id) {
  return CFG.voice.modes[id] ?? CFG.voice.modes[CFG.voice.defaultMode];
}

/** เพดานเวลาที่ยอมล็อกปุ่ม "เล่นอีกครั้ง" ไว้รอเสียงเฉลย (ดูเหตุผลที่ CFG.audio) */
export function narrationCapMs(text = '') {
  const a = CFG.audio;
  return Math.min(
    a.narrationCapMaxMs,
    a.narrationCapBaseMs + text.length * a.narrationCapPerCharMs,
  );
}

/** กติกาความยากของสิ่งกีดขวาง ณ จำนวนด่านที่ผ่านมาแล้ว */
export function obstacleRuleFor(gatesPassed) {
  let rule = CFG.pacing.obstacleRamp[0];
  for (const r of CFG.pacing.obstacleRamp) {
    if (gatesPassed >= r.afterGates) rule = r;
  }
  return { ...rule, lead: Math.max(CFG.pacing.obstacleLeadFloor, rule.lead) };
}
