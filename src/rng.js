/**
 * rng.js — ตัวสุ่มที่ "สั่งให้ซ้ำรอยเดิมได้" (seeded PRNG)
 *
 * ── ทำไมต้องมี ──
 * Math.random() ให้เลขคนละชุดกันทุกเครื่อง — ปกติดี แต่ตอน "รอบชิง" ของ Battle Royale
 * เราต้องการให้ทุกคนเจอด่าน/อุปสรรค/เหรียญ "ชุดเดียวกันเป๊ะ" เพื่อให้โกสต์ของเพื่อน
 * ที่วิ่งอยู่ข้าง ๆ กลายเป็นเพื่อนที่อยู่ในโลกเดียวกันจริง ๆ ไม่ใช่ภาพลวง
 *
 * วิธีที่ถูกคือส่ง "เมล็ด" (seed) ตัวเดียวให้ทุกเครื่อง แล้วให้ทุกเครื่องสุ่มด้วย
 * อัลกอริทึมเดียวกันจากเมล็ดนั้น → ได้ลำดับเลขเหมือนกันทุกตัวโดยไม่ต้องส่งอะไรเพิ่มอีกเลย
 *
 * ⚠️ กฎเหล็กของ deterministic: ทุกการเรียก rng() ต้องเกิด "ลำดับเดียวกัน" ทุกเครื่อง
 *    ถ้าเครื่องไหนแอบเรียกเพิ่ม/ข้ามไปหนึ่งครั้ง ลำดับจะเหลื่อมกันทั้งสายทันที
 *    → ห้ามใช้ rng ของรอบชิงไปสุ่มอย่างอื่นที่ไม่ใช่ "ตัวโลก" เด็ดขาด
 *
 * mulberry32: PRNG 32 บิตที่สั้นที่สุดที่ยังกระจายตัวดีพอสำหรับงานเกม
 * (ไม่ปลอดภัยเชิงรหัสลับ — แต่เราไม่ได้ใช้ทำอะไรที่ต้องปลอดภัย)
 */

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function rng() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** เมล็ดสุ่มใหม่สำหรับหัวห้องกระจายให้ทุกคน */
export function randomSeed() {
  return (Math.random() * 0xffffffff) >>> 0;
}
